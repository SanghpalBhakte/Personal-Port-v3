export interface Project {
  id: string;
  number: string;
  kind: string;
  title: string;
  description: string;
  note?: string;
  status: string;
  tags: string[];
  link?: string;
  linkText?: string;
  /** Screenshot in /public/projects, captured from the live app. */
  image?: string;
  imageAlt?: string;
  /** Internal case-study route, e.g. /work/scheme-setu */
  caseStudy?: string;
}

export interface NoteItem {
  number: string;
  title: string;
  description: string;
}

export interface VisualWorkItem {
  id: string;
  title: string;
  url: string;
  /** Local cover in /public/design, generated by `npm run covers`. */
  image: string;
  /** Published year from Behance; "" until filled in. */
  year: string;
  /** Spans two columns on desktop. */
  featured?: boolean;
  category?: string;
  eyebrow?: string;
  description?: string;
  ctaText?: string;
}

export interface ToolGroup {
  category: string;
  items: string;
}

export interface ArchiveLink {
  title: string;
  platform: string;
  url: string;
}

export interface ContactPayload {
  name: string;
  email: string;
  message: string;
  _gotcha?: string;
}

export interface ContactResponse {
  success: boolean;
  message: string;
  submissionId?: string;
  errors?: Record<string, string[]>;
  /** Set when the note could not be delivered anywhere durable (no email / no Redis configured). */
  code?: "delivery_unavailable";
}

export interface HealthResponse {
  status: "ok" | "degraded" | "error";
  uptime: number;
  timestamp: string;
  service: string;
  environment: string;
  features: {
    redis: boolean;
    resend: boolean;
  };
}
